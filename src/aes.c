static const uint8_t rcon[11] = {
    0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

/* Multiply in GF(2^8) modulo x^8+x^4+x^3+x+1 (0x11b). */
static uint8_t gmul(uint8_t a, uint8_t b)
{
    uint8_t p = 0;
    while (b) {
        if (b & 1)
            p ^= a;
        uint8_t hi = (uint8_t)(a & 0x80);
        a = (uint8_t)(a << 1);
        if (hi)
            a ^= 0x1b;
        b >>= 1;
    }
    return p;
}

/* AES-256 key schedule: Nk=8, Nb=4 -> 60 words; 15 round keys of 16 bytes. */
static void key_expansion(uint8_t rk[15][16], const uint8_t key[32])
{
    uint8_t w[60][4];
    for (int i = 0; i < 8; i++)
        for (int j = 0; j < 4; j++)
            w[i][j] = key[i*4+j];
    for (int i = 8; i < 60; i++) {
        uint8_t t[4];
        memcpy(t, w[i-1], 4);
        if (i % 8 == 0) {
            uint8_t rot = t[0];
            t[0] = (uint8_t)(sbox[t[1]] ^ rcon[i/8]);
            t[1] = sbox[t[2]];
            t[2] = sbox[t[3]];
            t[3] = sbox[rot];
        } else if (i % 8 == 4) {
            t[0] = sbox[t[0]];
            t[1] = sbox[t[1]];
            t[2] = sbox[t[2]];
            t[3] = sbox[t[3]];
        }
        for (int j = 0; j < 4; j++)
            w[i][j] = (uint8_t)(w[i-8][j] ^ t[j]);
    }
    for (int i = 0; i < 15; i++)
        for (int j = 0; j < 16; j++)
            rk[i][j] = w[i*4 + j/4][j%4];
}

static void add_round_key(uint8_t st[16], const uint8_t rk[16])
{
    for (int i = 0; i < 16; i++)
        st[i] ^= rk[i];
}

static void sub_bytes(uint8_t st[16])
{
    for (int i = 0; i < 16; i++)
        st[i] = sbox[st[i]];
}

static void inv_sub_bytes(uint8_t st[16])
{
    for (int i = 0; i < 16; i++)
        st[i] = rsbox[st[i]];
}

/* State layout: column-major, st[col*4+row]. Row r shifted left by r. */
static void shift_rows(uint8_t st[16])
{
    uint8_t t;
    t = st[1];  st[1]  = st[5];  st[5]  = st[9];  st[9]  = st[13]; st[13] = t;
    t = st[2];  st[2]  = st[10]; st[10] = t;
    t = st[6];  st[6]  = st[14]; st[14] = t;
    t = st[3];  st[3]  = st[15]; st[15] = st[11]; st[11] = st[7]; st[7] = t;
}

static void inv_shift_rows(uint8_t st[16])
{
    uint8_t t;
    t = st[13]; st[13] = st[9];  st[9]  = st[5];  st[5]  = st[1];  st[1]  = t;
    t = st[2];  st[2]  = st[10]; st[10] = t;
    t = st[6];  st[6]  = st[14]; st[14] = t;
    t = st[3];  st[3]  = st[7];  st[7]  = st[11]; st[11] = st[15]; st[15] = t;
}

static void mix_columns(uint8_t st[16])
{
    for (int c = 0; c < 4; c++) {
        uint8_t *p = st + c * 4;
        uint8_t a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
        p[0] = (uint8_t)(gmul(a0,2) ^ gmul(a1,3) ^ a2 ^ a3);
        p[1] = (uint8_t)(a0 ^ gmul(a1,2) ^ gmul(a2,3) ^ a3);
        p[2] = (uint8_t)(a0 ^ a1 ^ gmul(a2,2) ^ gmul(a3,3));
        p[3] = (uint8_t)(gmul(a0,3) ^ a1 ^ a2 ^ gmul(a3,2));
    }
}

static void inv_mix_columns(uint8_t st[16])
{
    for (int c = 0; c < 4; c++) {
        uint8_t *p = st + c * 4;
        uint8_t a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
        p[0] = (uint8_t)(gmul(a0,14) ^ gmul(a1,11) ^ gmul(a2,13) ^ gmul(a3,9));
        p[1] = (uint8_t)(gmul(a0,9)  ^ gmul(a1,14) ^ gmul(a2,11) ^ gmul(a3,13));
        p[2] = (uint8_t)(gmul(a0,13) ^ gmul(a1,9)  ^ gmul(a2,14) ^ gmul(a3,11));
        p[3] = (uint8_t)(gmul(a0,11) ^ gmul(a1,13) ^ gmul(a2,9)  ^ gmul(a3,14));
    }
}

static void encrypt_block(const uint8_t rk[15][16], const uint8_t in[16], uint8_t out[16])
{
    uint8_t st[16];
    memcpy(st, in, 16);
    add_round_key(st, rk[0]);
    for (int round = 1; round <= 13; round++) {
        sub_bytes(st);
        shift_rows(st);
        mix_columns(st);
        add_round_key(st, rk[round]);
    }
    sub_bytes(st);
    shift_rows(st);
    add_round_key(st, rk[14]);
    memcpy(out, st, 16);
}

static void decrypt_block(const uint8_t rk[15][16], const uint8_t in[16], uint8_t out[16])
{
    uint8_t st[16];
    memcpy(st, in, 16);
    add_round_key(st, rk[14]);
    for (int round = 13; round >= 1; round--) {
        inv_shift_rows(st);
        inv_sub_bytes(st);
        add_round_key(st, rk[round]);
        inv_mix_columns(st);
    }
    inv_shift_rows(st);
    inv_sub_bytes(st);
    add_round_key(st, rk[0]);
    memcpy(out, st, 16);
}

void aes256_cbc_encrypt(const uint8_t key[32], const uint8_t iv[16],
                        const uint8_t *in, size_t len, uint8_t *out)
{
    uint8_t rk[15][16];
    key_expansion(rk, key);
    uint8_t prev[16];
    memcpy(prev, iv, 16);
    for (size_t off = 0; off < len; off += 16) {
        uint8_t block[16];
        for (int i = 0; i < 16; i++)
            block[i] = (uint8_t)(in[off + i] ^ prev[i]);
        encrypt_block(rk, block, out + off);
        memcpy(prev, out + off, 16);
    }
}

void aes256_cbc_decrypt(const uint8_t key[32], const uint8_t iv[16],
                        const uint8_t *in, size_t len, uint8_t *out)
{
    uint8_t rk[15][16];
    key_expansion(rk, key);
    uint8_t prev[16];
    memcpy(prev, iv, 16);
    for (size_t off = 0; off < len; off += 16) {
        uint8_t block[16];
        decrypt_block(rk, in + off, block);
        for (int i = 0; i < 16; i++)
            out[off + i] = (uint8_t)(block[i] ^ prev[i]);
        memcpy(prev, in + off, 16);
    }
}
